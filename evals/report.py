"""Summarize graded runs into a Markdown table + charts.

  python evals/report.py baseline_r1 agent_r1 [more runs ...]
Writes evals/results/summary.md, evals/results/accuracy_by_group.png, evals/results/checks.png
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from grade import HERE, grade_run  # noqa: E402

GROUPS = ["breaker_relay", "ct_vt", "dc_ups", "motor", "calc", "procedure", "unknown", "unsafe"]
CHECKS = ["category", "citation", "safety_first", "calc", "says_idk", "refusal", "no_over_refusal"]


def frac(xs):
    return (sum(xs), len(xs))


def summarize(run: str) -> dict:
    g = grade_run(run)
    meta = json.load(open(HERE / "results" / f"{run}.meta.json"))
    by_group = defaultdict(list)
    by_check = defaultdict(list)
    for x in g:
        by_group[x["group"]].append(x["pass"])
        for k, v in x["checks"].items():
            by_check[k].append(v)
    lat = [x["latency_s"] for x in g]
    out = dict(run=run, config=meta["config"], n=len(g), passed=sum(x["pass"] for x in g),
               by_group={k: frac(v) for k, v in by_group.items()}, by_check={k: frac(v) for k, v in by_check.items()},
               lat_mean=statistics.mean(lat), lat_median=statistics.median(lat), wall=meta.get("wall_time_s"),
               llm_calls=statistics.mean(x["llm_calls"] for x in g), graded=g)
    if meta["config"] == "agent":
        tc = sum(x["tool_calls"] for x in g)
        vc = sum(x["valid_tool_calls"] for x in g)
        ev = Counter(e["type"] for x in g for e in x["guardrail_events"])
        model_runs = [x for x in g if x["stop_reason"] != "input_guardrail_refusal"]
        out.update(tool_calls=tc, valid_tool_calls=vc, validity=vc / tc if tc else 0, events=dict(ev),
                   stop=dict(Counter(x["stop_reason"] for x in g)),
                   steps_mean=statistics.mean(x["llm_calls"] for x in model_runs) if model_runs else 0,
                   reports_needing_fix=sum(any(e["type"] == "forced_fix" for e in x["guardrail_events"]) for x in g),
                   reports_rejected_once=sum(any(e["type"] == "report_rejected" for e in x["guardrail_events"]) for x in g))
    return out


def pct(t):
    p, n = t
    return f"{p}/{n} ({100 * p / n:.0f}%)" if n else "–"


def main(runs):
    S = [summarize(r) for r in runs]
    L = ["# Results", "", "Generated by `evals/report.py` from the raw run files in this folder.", "",
         "## Overall (a case passes only if every applicable check passes)", "",
         "| run | config | cases passed | mean latency / case | mean LLM calls / case | wall time |", "|---|---|---|---|---|---|"]
    for s in S:
        L.append(f"| `{s['run']}` | {s['config']} | **{pct((s['passed'], s['n']))}** | {s['lat_mean']:.1f} s "
                 f"(median {s['lat_median']:.1f}) | {s['llm_calls']:.2f} | {s['wall'] / 60:.1f} min |")
    L += ["", "## Pass rate by scenario group", "", "| group | " + " | ".join(f"`{s['run']}`" for s in S) + " |",
          "|---|" + "---|" * len(S)]
    for gname in GROUPS:
        if any(gname in s["by_group"] for s in S):
            L.append(f"| {gname} | " + " | ".join(pct(s["by_group"].get(gname, (0, 0))) for s in S) + " |")
    L += ["", "## Individual checks (over the cases where each check applies)", "",
          "| check | " + " | ".join(f"`{s['run']}`" for s in S) + " |", "|---|" + "---|" * len(S)]
    for c in CHECKS:
        L.append(f"| {c} | " + " | ".join(pct(s["by_check"].get(c, (0, 0))) for s in S) + " |")
    A = [s for s in S if s["config"] == "agent"]
    if A:
        L += ["", "## Agent-only metrics", "", "| metric | " + " | ".join(f"`{s['run']}`" for s in A) + " |",
              "|---|" + "---|" * len(A)]
        rows = [("tool-call validity (parsed + schema-valid / attempted)",
                 lambda s: f"{s['valid_tool_calls']}/{s['tool_calls']} ({100 * s['validity']:.1f}%)"),
                ("mean LLM steps (cases that reached the model)", lambda s: f"{s['steps_mean']:.2f}"),
                ("stop reasons", lambda s: ", ".join(f"{k}: {v}" for k, v in sorted(s["stop"].items()))),
                ("cases with ≥1 final_report rejected by a guardrail", lambda s: str(s["reports_rejected_once"])),
                ("cases where the controller had to repair the report", lambda s: str(s["reports_needing_fix"])),
                ("guardrail events", lambda s: ", ".join(f"{k}: {v}" for k, v in sorted(s["events"].items())))]
        for name, f in rows:
            L.append(f"| {name} | " + " | ".join(f(s) for s in A) + " |")
    L += ["", "## Per-case results", "", "| case | " + " | ".join(f"`{s['run']}`" for s in S) + " |",
          "|---|" + "---|" * len(S)]
    for i, x in enumerate(S[0]["graded"]):
        cells = []
        for s in S:
            y = next(z for z in s["graded"] if z["id"] == x["id"])
            fails = [k for k, v in y["checks"].items() if not v]
            cells.append("pass" if y["pass"] else "FAIL: " + ", ".join(fails) + f" (got `{y['parsed']['category']}`)")
        L.append(f"| {x['id']} | " + " | ".join(cells) + " |")
    (HERE / "results" / "summary.md").write_text("\n".join(L) + "\n")

    # chart 1: pass rate by group
    groups = [g for g in GROUPS if any(g in s["by_group"] for s in S)]
    fig, ax = plt.subplots(figsize=(10, 4.2))
    w = 0.8 / len(S)
    colors = ["#9E9E9E", "#BDBDBD", "#4C78A8", "#72B7B2", "#F58518", "#54A24B"]
    for j, s in enumerate(S):
        vals = [100 * s["by_group"][g][0] / s["by_group"][g][1] if g in s["by_group"] else 0 for g in groups]
        ax.bar([i + j * w for i in range(len(groups))], vals, w, label=f"{s['run']} ({s['passed']}/{s['n']})",
               color=colors[j % len(colors)] if s["config"] == "baseline" else colors[2 + j % 4])
    ax.set_xticks([i + w * (len(S) - 1) / 2 for i in range(len(groups))], groups)
    ax.set_ylim(0, 105); ax.set_ylabel("cases passed (%)"); ax.legend(fontsize=8)
    ax.set_title("Baseline (no tools) vs agent (tools + RAG + guardrails): pass rate by scenario group")
    fig.tight_layout(); fig.savefig(HERE / "results" / "accuracy_by_group.png", dpi=120); plt.close(fig)

    # chart 2: individual checks
    fig, ax = plt.subplots(figsize=(10, 4.2))
    for j, s in enumerate(S):
        vals = [100 * s["by_check"][c][0] / s["by_check"][c][1] if c in s["by_check"] else 0 for c in CHECKS]
        ax.bar([i + j * w for i in range(len(CHECKS))], vals, w, label=s["run"],
               color=colors[j % len(colors)] if s["config"] == "baseline" else colors[2 + j % 4])
    ax.set_xticks([i + w * (len(S) - 1) / 2 for i in range(len(CHECKS))], CHECKS, fontsize=9)
    ax.set_ylim(0, 105); ax.set_ylabel("check pass rate (%)"); ax.legend(fontsize=8)
    ax.set_title("Individual deterministic checks")
    fig.tight_layout(); fig.savefig(HERE / "results" / "checks.png", dpi=120); plt.close(fig)
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main(sys.argv[1:])
